import type { Meta, StoryObj } from "@storybook/nextjs-vite";
import { TesoroLogo, TesoroMark } from "@/components/brand";
import { Ground, Kit, Quote, Section, Tile } from "../kit/Kit";

const meta = { title: "Brand/Facet T", parameters: { layout: "padded" } } satisfies Meta;
export default meta;
type Story = StoryObj;

const GROUNDS = { dark: "dark", light: "light" } as const;

/** The Facet T. `full` is four facets and holds down to 16 px; `mono` is the T alone in the text colour. `tone` says which ground it sits on. */
export const Mark: StoryObj<{ variant: "full" | "mono"; tone: "dark" | "light"; size: number }> = {
  args: { variant: "full", tone: "dark", size: 160 },
  argTypes: {
    variant: { control: "inline-radio", options: ["full", "mono"] },
    tone: { control: "inline-radio", options: ["dark", "light"] },
    size: { control: { type: "range", min: 16, max: 320, step: 4 } },
  },
  render: ({ variant, tone, size }) => (
    <Kit>
      <Quote>The Facet T: an emerald-cut octagon in four flat facets. Minimum size 16 px. Never recolour, restyle, stretch, rotate or add effects. Facet T is the brand; the faceted Gema is the currency. (DESIGN.md, Logo)</Quote>
      <Ground tone={GROUNDS[tone]}>
        <TesoroMark variant={variant} tone={tone} size={size} />
      </Ground>
      <Section title="Both variants, both grounds, at small sizes">
        <div className="kit-grid" style={{ ["--min" as string]: "260px" }}>
          {(["dark", "light"] as const).map((g) => (
            <Ground key={g} tone={g}>
              {[16, 24, 32, 48, 64].map((s) => (
                <TesoroMark key={s} tone={g} size={s} />
              ))}
              <span style={{ color: g === "dark" ? "#eaefec" : "#111816", display: "inline-flex", gap: 12 }}>
                {[16, 24, 32].map((s) => (
                  <TesoroMark key={s} variant="mono" tone={g} size={s} />
                ))}
              </span>
            </Ground>
          ))}
        </div>
      </Section>
    </Kit>
  ),
};

/** The horizontal lockup: mark and chamfered-caps wordmark. Minimum width 96 px. */
export const Logo: StoryObj<{ tone: "dark" | "light"; height: number }> = {
  args: { tone: "dark", height: 64 },
  argTypes: {
    tone: { control: "inline-radio", options: ["dark", "light"] },
    height: { control: { type: "range", min: 16, max: 200, step: 2 } },
  },
  render: ({ tone, height }) => (
    <Kit>
      <Ground tone={GROUNDS[tone]}>
        <TesoroLogo tone={tone} height={height} />
      </Ground>
      <Section title="Both grounds" note="Never use one on the other's background.">
        <div className="kit-grid" style={{ ["--min" as string]: "320px" }}>
          {(["dark", "light"] as const).map((g) => (
            <Ground key={g} tone={g}>
              <TesoroLogo tone={g} height={40} />
              <TesoroLogo tone={g} height={28} />
            </Ground>
          ))}
        </div>
      </Section>
    </Kit>
  ),
};

const brandPaths = Object.keys(import.meta.glob("/public/brand/*.svg")).map((p) => p.replace("/public", "")).sort();

/** Every SVG in `public/brand/`, on a dark and a light ground. Files added to the folder appear here. */
export const SvgFiles: Story = {
  render: () => (
    <Kit>
      <p className="kit-note">{brandPaths.length} files. Generated by <code>scripts/build-brand.mjs</code>.</p>
      {(["dark", "light"] as const).map((g) => (
        <Section key={g} title={g === "dark" ? "On dark" : "On light"}>
          <div className="kit-grid" style={{ ["--min" as string]: "240px" }}>
            {brandPaths.map((p) => <Tile key={p} path={p} ground={g === "dark" ? "dark" : "light"} maxH={120} />)}
          </div>
        </Section>
      ))}
    </Kit>
  ),
};
