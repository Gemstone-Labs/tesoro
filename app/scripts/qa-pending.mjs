/** Wallet with "Pending by Source" expanded. node scripts/qa-pending.mjs <dev> <shotname> [width] */
import { createRequire } from "node:module";
import { readFileSync } from "node:fs";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PW);
const [dev, name, w = "390"] = process.argv.slice(2);
const keys = JSON.parse(readFileSync(`${process.env.HOME}/.cache/tesoro-tmp/e2e-hype/devkeys.json`, "utf8"));
const b = await chromium.launch({ executablePath: "/usr/bin/chromium", args: ["--no-sandbox"] });
const ctx = await b.newContext({ viewport: { width: Number(w), height: 844 } });
await ctx.addInitScript(([d, k]) => { localStorage.setItem(`tesoro-dev-wallet:${d}`, k.sol); localStorage.setItem(`tesoro-dev-evm:${d}`, k.evm); localStorage.setItem("tesoro-guide-dismissed", JSON.stringify(["wallet-first","redeem","gemas","xc-open"])); }, [dev, keys[dev]]);
const p = await ctx.newPage(); p.setDefaultTimeout(90000);
await p.goto(`http://localhost:3152/wallet?dev=${dev}`, { waitUntil: "load" });
await p.waitForFunction(() => /Total Balance/.test(document.body.innerText) && !/Reading Positions/.test(document.body.innerText), null, { timeout: 90000 }).catch(() => {});
await p.waitForTimeout(Number(process.env.WAIT ?? 30000));
await p.getByText("Pending by Source").click().catch(() => {});
await p.waitForTimeout(800);
console.log((await p.locator("main").innerText()).split("\n").filter(Boolean).join(" | ").slice(0, 1800));
await p.evaluate(async () => { for (let y = 0; y < document.body.scrollHeight; y += 400) { window.scrollTo(0, y); await new Promise((r) => setTimeout(r, 120)); } window.scrollTo(0, 0); });
await p.waitForTimeout(800);
await p.screenshot({ path: `${process.cwd()}/docs/screens/qa-2026-10-02-hype-${name}.png`, fullPage: true });
console.log("overflow px:", await p.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth));
await b.close();
