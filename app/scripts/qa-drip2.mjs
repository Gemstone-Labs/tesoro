import { createRequire } from "node:module";
import { readFileSync } from "node:fs";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PW);
const dev = process.argv[2];
const keys = JSON.parse(readFileSync(`${process.env.HOME}/.cache/tesoro-tmp/e2e-hype/devkeys.json`, "utf8"));
const b = await chromium.launch({ executablePath: "/usr/bin/chromium", args: ["--no-sandbox"] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
await ctx.addInitScript(([d, k]) => { localStorage.setItem(`tesoro-dev-wallet:${d}`, k.sol); localStorage.setItem(`tesoro-dev-evm:${d}`, k.evm); localStorage.setItem("tesoro-guide-dismissed", JSON.stringify(["wallet-first","redeem","gemas","xc-open"])); }, [dev, keys[dev]]);
const p = await ctx.newPage(); p.setDefaultTimeout(90000);
await p.goto(`http://localhost:3152/wallet?dev=${dev}`, { waitUntil: "load", timeout: 180000 });
await p.getByRole("button", { name: "Open a Position" }).first().click();
await p.getByRole("tab", { name: "HYPE" }).click();
await p.getByRole("button", { name: "Get test HYPE" }).waitFor({ timeout: 90000 });
await p.screenshot({ path: `${process.cwd()}/docs/screens/qa-2026-10-02-hype-drip2-before.png`, fullPage: true });
await p.getByRole("button", { name: "Get test HYPE" }).click();
await p.waitForTimeout(15000);
console.log((await p.locator("body").innerText()).split("\n").filter((l) => /HYPE|limit|day|empty|wait|again|error|refus/i.test(l)).join(" | "));
